-- Base hospital_citas: solo el servicio de citas accede a esta tabla.
-- paciente_id es una referencia lógica al servicio de pacientes (otra base): no se declara FOREIGN KEY.
CREATE TABLE IF NOT EXISTS cita (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(12)  NOT NULL,
    paciente_id         BIGINT       NOT NULL,
    especialidad        VARCHAR(30)  NOT NULL,
    fecha_hora          TIMESTAMP    NOT NULL,
    profesional_codigo  VARCHAR(7)   NOT NULL,
    motivo              VARCHAR(200),
    estado              VARCHAR(12)  NOT NULL,
    fecha_creacion      TIMESTAMP    NOT NULL,
    fecha_actualizacion TIMESTAMP,
    CONSTRAINT uk_cita_codigo UNIQUE (codigo),
    CONSTRAINT ck_cita_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'ATENDIDA', 'CANCELADA', 'AUSENTE'))
);

-- Búsquedas por paciente y validación de horarios ocupados (RN-05)
CREATE INDEX IF NOT EXISTS idx_cita_paciente ON cita (paciente_id, fecha_hora);
CREATE INDEX IF NOT EXISTS idx_cita_profesional ON cita (profesional_codigo, fecha_hora);
