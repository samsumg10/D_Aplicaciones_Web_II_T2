-- Base hospital_hospitalizacion. paciente_id es una referencia lógica al servicio de pacientes.
CREATE TABLE IF NOT EXISTS hospitalizacion (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                VARCHAR(12)  NOT NULL,
    paciente_id           BIGINT       NOT NULL,
    area                  VARCHAR(20)  NOT NULL,
    motivo_administrativo VARCHAR(200),
    cama_codigo           VARCHAR(7),
    -- RN-09: tiene valor solo mientras la hospitalización está ACTIVA. Al ser UNIQUE, una cama no puede
    -- estar en dos hospitalizaciones activas; los null (solicitadas, altas, canceladas) no chocan entre sí.
    cama_ocupada          VARCHAR(7),
    estado                VARCHAR(12)  NOT NULL,
    fecha_solicitud       TIMESTAMP    NOT NULL,
    fecha_ingreso         TIMESTAMP,
    fecha_alta            TIMESTAMP,
    fecha_actualizacion   TIMESTAMP,
    CONSTRAINT uk_hospitalizacion_codigo UNIQUE (codigo),
    CONSTRAINT uk_hospitalizacion_cama_ocupada UNIQUE (cama_ocupada),
    CONSTRAINT ck_hospitalizacion_estado CHECK (estado IN ('SOLICITADA', 'ACTIVA', 'ALTA', 'CANCELADA'))
);

CREATE INDEX IF NOT EXISTS idx_hospitalizacion_paciente ON hospitalizacion (paciente_id, estado);
