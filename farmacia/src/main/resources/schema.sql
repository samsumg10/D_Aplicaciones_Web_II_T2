-- Base hospital_farmacia: catálogo y dispensaciones de demostración (sin valor clínico).
CREATE TABLE IF NOT EXISTS medicamento (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(8)   NOT NULL,
    nombre              VARCHAR(100) NOT NULL,
    presentacion        VARCHAR(100) NOT NULL,
    stock               INTEGER      NOT NULL,
    fecha_registro      TIMESTAMP    NOT NULL,
    fecha_actualizacion TIMESTAMP,
    CONSTRAINT uk_medicamento_codigo UNIQUE (codigo),
    -- RN-10: el stock nunca queda negativo, ni siquiera por un error de programación
    CONSTRAINT ck_medicamento_stock CHECK (stock >= 0)
);

-- medicamento_id se relaciona con una tabla de la MISMA base, por eso aquí sí hay clave foránea.
CREATE TABLE IF NOT EXISTS dispensacion (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                    VARCHAR(12) NOT NULL,
    medicamento_id            BIGINT      NOT NULL,
    paciente_id               BIGINT      NOT NULL,
    cantidad                  INTEGER     NOT NULL,
    referencia_administrativa VARCHAR(30) NOT NULL,
    estado                    VARCHAR(12) NOT NULL,
    fecha_dispensacion        TIMESTAMP   NOT NULL,
    fecha_actualizacion       TIMESTAMP,
    CONSTRAINT uk_dispensacion_codigo UNIQUE (codigo),
    CONSTRAINT fk_dispensacion_medicamento FOREIGN KEY (medicamento_id) REFERENCES medicamento (id),
    CONSTRAINT ck_dispensacion_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_dispensacion_estado CHECK (estado IN ('REGISTRADA', 'ANULADA'))
);

CREATE INDEX IF NOT EXISTS idx_dispensacion_paciente ON dispensacion (paciente_id, fecha_dispensacion);
