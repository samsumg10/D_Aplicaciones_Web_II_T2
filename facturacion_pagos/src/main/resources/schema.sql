-- Base hospital_facturacion: cargos administrativos y pagos simulados.
-- paciente_id y atencion_id son referencias lógicas a otros servicios (sin FOREIGN KEY entre bases).
CREATE TABLE IF NOT EXISTS cargo (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(12)   NOT NULL,
    paciente_id         BIGINT        NOT NULL,
    atencion_id         BIGINT,
    concepto            VARCHAR(150)  NOT NULL,
    monto               NUMERIC(10,2) NOT NULL,
    estado              VARCHAR(10)   NOT NULL,
    fecha_registro      TIMESTAMP     NOT NULL,
    fecha_actualizacion TIMESTAMP,
    CONSTRAINT uk_cargo_codigo UNIQUE (codigo),
    CONSTRAINT ck_cargo_monto CHECK (monto > 0),
    CONSTRAINT ck_cargo_estado CHECK (estado IN ('PENDIENTE', 'PAGADO', 'ANULADO'))
);

-- cargo_id apunta a una tabla de la MISMA base: aquí sí corresponde una clave foránea.
CREATE TABLE IF NOT EXISTS pago (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cargo_id          BIGINT        NOT NULL,
    paciente_id       BIGINT        NOT NULL,
    concepto          VARCHAR(150)  NOT NULL,
    monto             NUMERIC(10,2) NOT NULL,
    medio_pago        VARCHAR(20)   NOT NULL,
    numero_operacion  VARCHAR(20)   NOT NULL,
    estado            VARCHAR(12)   NOT NULL,
    fecha_pago        TIMESTAMP     NOT NULL,
    -- RN-11: no se duplica el número de operación y el monto siempre es positivo
    CONSTRAINT uk_pago_numero_operacion UNIQUE (numero_operacion),
    CONSTRAINT ck_pago_monto CHECK (monto > 0),
    CONSTRAINT fk_pago_cargo FOREIGN KEY (cargo_id) REFERENCES cargo (id)
);

CREATE INDEX IF NOT EXISTS idx_cargo_paciente ON cargo (paciente_id, fecha_registro);
CREATE INDEX IF NOT EXISTS idx_pago_paciente ON pago (paciente_id, fecha_pago);
