-- Base hospital_atenciones. paciente_id y cita_id son referencias lógicas a otros servicios (sin FOREIGN KEY).
CREATE TABLE IF NOT EXISTS atencion (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(12)  NOT NULL,
    paciente_id         BIGINT       NOT NULL,
    cita_id             BIGINT       NOT NULL,
    area                VARCHAR(20)  NOT NULL,
    observacion         VARCHAR(200),
    estado              VARCHAR(12)  NOT NULL,
    fecha_atencion      TIMESTAMP    NOT NULL,
    fecha_actualizacion TIMESTAMP,
    CONSTRAINT uk_atencion_codigo UNIQUE (codigo),
    -- RN-07: una sola atención por cita
    CONSTRAINT uk_atencion_cita UNIQUE (cita_id),
    CONSTRAINT ck_atencion_estado CHECK (estado IN ('REGISTRADA', 'FINALIZADA', 'ANULADA'))
);

CREATE INDEX IF NOT EXISTS idx_atencion_paciente ON atencion (paciente_id, fecha_atencion);
