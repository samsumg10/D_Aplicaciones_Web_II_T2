-- Base hospital_notificaciones: avisos simulados generados a partir de eventos de RabbitMQ.
CREATE TABLE IF NOT EXISTS notificacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id       VARCHAR(36)  NOT NULL,
    tipo_evento     VARCHAR(60)  NOT NULL,
    paciente_id     BIGINT,
    recurso         VARCHAR(30),
    recurso_id      VARCHAR(30),
    canal           VARCHAR(20)  NOT NULL,
    asunto          VARCHAR(100) NOT NULL,
    mensaje         VARCHAR(300),
    estado          VARCHAR(20)  NOT NULL,
    fecha_evento    TIMESTAMP,
    fecha_registro  TIMESTAMP    NOT NULL,
    -- Idempotencia: una entrega duplicada del mismo evento no genera un segundo aviso
    CONSTRAINT uk_notificacion_evento UNIQUE (evento_id)
);

CREATE INDEX IF NOT EXISTS idx_notificacion_paciente ON notificacion (paciente_id, fecha_registro);
