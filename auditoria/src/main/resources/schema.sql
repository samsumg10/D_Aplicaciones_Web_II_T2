-- Base hospital_auditoria: traza de los cambios importantes de todos los servicios (solo inserciones).
CREATE TABLE IF NOT EXISTS registro_auditoria (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id        VARCHAR(36)  NOT NULL,
    tipo_evento      VARCHAR(60)  NOT NULL,
    origen           VARCHAR(30)  NOT NULL,
    recurso          VARCHAR(30)  NOT NULL,
    recurso_id       VARCHAR(30)  NOT NULL,
    paciente_id      BIGINT,
    estado_anterior  VARCHAR(20),
    estado_nuevo     VARCHAR(20),
    detalle          VARCHAR(300),
    fecha_evento     TIMESTAMP    NOT NULL,
    fecha_registro   TIMESTAMP    NOT NULL,
    -- Idempotencia: el mismo evento no se audita dos veces
    CONSTRAINT uk_auditoria_evento UNIQUE (evento_id)
);

CREATE INDEX IF NOT EXISTS idx_auditoria_recurso ON registro_auditoria (recurso, recurso_id, fecha_evento);
CREATE INDEX IF NOT EXISTS idx_auditoria_paciente ON registro_auditoria (paciente_id, fecha_evento);
