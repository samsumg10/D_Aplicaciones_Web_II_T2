package com.example.pacientes.domain;

/** Documentos aceptados. Los números usados en el proyecto son siempre ficticios. */
public enum TipoDocumento {
    /** Documento nacional de identidad: 8 dígitos. */
    DNI,
    /** Carné de extranjería: 9 a 12 caracteres alfanuméricos. */
    CE,
    /** Pasaporte: 6 a 12 caracteres alfanuméricos. */
    PASAPORTE
}
