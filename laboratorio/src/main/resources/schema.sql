-- Base hospital_laboratorio. paciente_id y atencion_id son referencias lógicas (sin FOREIGN KEY entre bases).
-- resultado_ficticio: texto de demostración sin valor clínico.
CREATE TABLE IF NOT EXISTS solicitud_laboratorio (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(12)  NOT NULL,
    paciente_id         BIGINT       NOT NULL,
    atencion_id         BIGINT       NOT NULL,
    tipo_examen         VARCHAR(20)  NOT NULL,
    estado              VARCHAR(12)  NOT NULL,
    resultado_ficticio  VARCHAR(300),
    fecha_solicitud     TIMESTAMP    NOT NULL,
    fecha_actualizacion TIMESTAMP,
    CONSTRAINT uk_solicitud_codigo UNIQUE (codigo),
    CONSTRAINT ck_solicitud_estado CHECK (estado IN ('SOLICITADO', 'EN_PROCESO', 'COMPLETADO', 'CANCELADO'))
);

CREATE INDEX IF NOT EXISTS idx_solicitud_paciente ON solicitud_laboratorio (paciente_id, fecha_solicitud);
CREATE INDEX IF NOT EXISTS idx_solicitud_atencion ON solicitud_laboratorio (atencion_id);
